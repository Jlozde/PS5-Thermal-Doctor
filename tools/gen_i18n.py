"""Generate src/texts.h and the web UI dictionary from tools/i18n_texts.py.
tools/i18n_texts.py dosyasından src/texts.h ve web arayüzü sözlüğünü üretir.

    python tools/gen_i18n.py           # write the files / dosyaları yaz
    python tools/gen_i18n.py --check   # fail if they are out of date (CI) / güncel değilse hata ver

It also checks the translations: every language must use the same printf
conversions (payload texts) or the same {n} placeholders (web texts), and every
key the web page uses must exist.
Çevirileri de denetler: her dil aynı printf dönüşümlerini (payload metinleri)
ya da aynı {n} yer tutucularını (web metinleri) kullanmalı ve sayfanın
kullandığı her anahtar tanımlı olmalıdır.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import i18n_texts as T  # noqa: E402

HEADER = os.path.join(ROOT, "src", "texts.h")
PAGE = os.path.join(ROOT, "web", "index.html")
BEGIN = "// <i18n> generated by tools/gen_i18n.py from tools/i18n_texts.py, do not edit by hand"
END = "// </i18n>"
CODES = [c for c, _, _ in T.LANGS]
PRINTF = re.compile(r"%(?:%|[-+ #0]*\d*(?:\.\d+)?(?:hh|h|ll|l|z)?[diouxXfFeEgGcsp])")
BRACE = re.compile(r"\{(\d+)\}")


def fail(msg):
    print("ERROR / HATA: " + msg)
    sys.exit(1)


def check():
    for table_name, table in (("SERVER", T.SERVER), ("WEB", T.WEB)):
        for key, vals in table.items():
            if len(vals) != len(CODES):
                fail(f"{table_name}[{key}] has {len(vals)} texts, needs {len(CODES)}")
            for code, v in zip(CODES, vals):
                if not isinstance(v, str):
                    fail(f"{table_name}[{key}][{code}] is not a string")
    for key, vals in T.SERVER.items():
        want = [c for c in PRINTF.findall(vals[0]) if c != "%%"]
        for code, v in zip(CODES, vals):
            got = [c for c in PRINTF.findall(v) if c != "%%"]
            if got != want:
                fail(f"SERVER[{key}][{code}] uses {got}, English uses {want}")
            if re.search(r"%(?!%|[-+ #0]*\d*(?:\.\d+)?[a-zA-Z])", v.replace("%%", "")):
                fail(f"SERVER[{key}][{code}] has a stray %")
    for key, vals in T.WEB.items():
        want = sorted(set(BRACE.findall(vals[0])))
        for code, v in zip(CODES, vals):
            if key == "log_lang":
                continue
            if sorted(set(BRACE.findall(v))) != want:
                fail(f"WEB[{key}][{code}] placeholders differ from English")
            if not v and code != "en":
                fail(f"WEB[{key}][{code}] is empty")


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def gen_header():
    out = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later",
        " *",
        " * Generated by tools/gen_i18n.py from tools/i18n_texts.py. Do not edit by hand.",
        " * tools/gen_i18n.py tarafından tools/i18n_texts.py dosyasından üretildi; elle düzenlemeyin.",
        " *",
        " * TX_<KEY>(lang) expands to a T8() choice of string literals, so the compiler",
        " * checks every language's format string against the arguments.",
        " */",
        "#ifndef PS5TD_TEXTS_H",
        "#define PS5TD_TEXTS_H",
        "",
        '#include "i18n.h"',
        "",
    ]
    for key, vals in T.SERVER.items():
        out.append(f"#define TX_{key.upper()}(l) T8((l), \\")
        for i, v in enumerate(vals):
            out.append(f"  {c_str(v)}" + (", \\" if i < len(vals) - 1 else ")"))
        out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def gen_block():
    lines = [BEGIN, "const LANGS = " + json.dumps([list(x) for x in T.LANGS], ensure_ascii=False) + ";", "const I18N = {"]
    for i, code in enumerate(CODES):
        d = {k: v[i] for k, v in T.WEB.items()}
        lines.append(f"  {code}: " + json.dumps(d, ensure_ascii=False) + ("," if i < len(CODES) - 1 else ""))
    lines += ["};", END]
    return "\n".join(lines)


def page_with_block(page):
    a, b = page.find(BEGIN), page.find(END)
    if a < 0 or b < 0:
        fail("web/index.html has no <i18n> block")
    new = page[:a] + gen_block() + page[b + len(END):]
    used = set(re.findall(r'data-i18n="([a-z0-9_]+)"', new)) | set(re.findall(r"\bt\('([a-z0-9_]+)'", new))
    # settings fields are looked up as f_<key> and h_<key>
    used |= {p + k for k in re.findall(r"\{k:'([a-z0-9_]+)'", new) for p in ("f_", "h_")}
    missing = sorted(k for k in used if k not in T.WEB and not k.endswith("_"))
    if missing:
        fail("web/index.html uses keys missing from WEB: " + ", ".join(missing))
    return new


def main():
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    check()
    header = gen_header()
    page = open(PAGE, encoding="utf-8").read()
    new_page = page_with_block(page)
    if "--check" in sys.argv:
        old_header = open(HEADER, encoding="utf-8").read() if os.path.exists(HEADER) else ""
        stale = [n for n, old, new in (("src/texts.h", old_header, header), ("web/index.html", page, new_page)) if old != new]
        if stale:
            fail("out of date, run python tools/gen_i18n.py: " + ", ".join(stale))
        print("i18n OK / TAMAM: %d languages, %d payload texts, %d web texts" % (len(CODES), len(T.SERVER), len(T.WEB)))
        return
    with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
    with open(PAGE, "w", encoding="utf-8", newline="\n") as f:
        f.write(new_page)
    print("written / yazıldı: src/texts.h, web/index.html (%d languages / dil)" % len(CODES))


if __name__ == "__main__":
    main()
